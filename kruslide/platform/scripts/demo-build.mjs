// Build the files of the clickable demo (DEMO_MODE): sample decks, fonts and quiz images as Workers Static Assets,
// plus src/demo/catalog.ts (books, units, CSP hashes, slide counts) for the demo seed.
//   node scripts/demo-build.mjs   -> demo/assets/ (git-ignored) and src/demo/catalog.ts
// The decks come from kruslide/samples/<slug>/index.html. Their font URLs (../_shared/fonts/…) are rewritten to
// fonts/… so they resolve to the platform's access-checked asset route /app/deck/<unit>/fonts/….
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SAMPLES = resolve(ROOT, '../samples');
const OUT = join(ROOT, 'demo/assets');

/** Three sample books; every unit is one sample deck. Ids are fixed so file keys and seed rows always match. */
const BOOKS = [
  { id: 1, title: 'คณิตศาสตร์ (ตัวอย่าง)', subject: 'คณิตศาสตร์', grade: 'ป.4–ม.6', rate: 3, slugs: ['calculus', 'math-fractions', 'math-equation-balance'] },
  { id: 2, title: 'วิทยาศาสตร์ (ตัวอย่าง)', subject: 'วิทยาศาสตร์', grade: 'ม.1–6', rate: 4, slugs: ['chem-periodic', 'phys-circuit', 'bio-cell'] },
  { id: 3, title: 'ภาษาไทย (ตัวอย่าง)', subject: 'ภาษาไทย', grade: 'ป.1–ม.3', rate: 3, slugs: ['thai-poem', 'thai-spelling'] },
];

// The same rules as src/lib/deckmeta.ts.
function scriptHashes(html) {
  const out = new Set();
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
    if (/\bsrc\s*=/i.test(m[1])) continue;
    const type = /\btype\s*=\s*["']?([^"'\s>]+)/i.exec(m[1])?.[1]?.toLowerCase();
    if (type && !['text/javascript', 'module', 'application/javascript'].includes(type)) continue;
    out.add(`'sha256-${createHash('sha256').update(m[2].replace(/\r\n?/g, '\n'), 'utf8').digest('base64')}'`);
  }
  return [...out];
}
function countSlides(html) {
  const markup = html.replace(/<script\b[^>]*>[\s\S]*?<\/script\s*>/gi, '').replace(/<!--[\s\S]*?-->/g, '');
  return (markup.match(/<section\b[^>]*class="(?:[^"]*\s)?slide(?:\s[^"]*)?"/g) || []).length;
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, 'shared/fonts'), { recursive: true });
mkdirSync(join(OUT, 'shared/quiz'), { recursive: true });
for (const f of readdirSync(join(SAMPLES, '_shared/fonts')).filter((n) => n.endsWith('.woff2'))) copyFileSync(join(SAMPLES, '_shared/fonts', f), join(OUT, 'shared/fonts', f));
for (const f of readdirSync(join(ROOT, 'quiz')).filter((n) => n.endsWith('.webp'))) copyFileSync(join(ROOT, 'quiz', f), join(OUT, 'shared/quiz', f));

let unitId = 0;
const catalog = BOOKS.map((b) => ({
  id: b.id, title: b.title, subject: b.subject, grade: b.grade, rate: b.rate,
  units: b.slugs.map((slug, i) => {
    unitId += 1;
    const dir = join(SAMPLES, slug);
    const meta = JSON.parse(readFileSync(join(dir, 'sample.json'), 'utf8'));
    let html = readFileSync(join(dir, 'index.html'), 'utf8').replaceAll('../_shared/fonts/', 'fonts/');
    if (/(src|href)\s*=\s*["'](?!data:|#|fonts\/)[^"']+\.(png|jpe?g|webp|svg|mp3|mp4|js|css)["']/i.test(html)) {
      throw new Error(`${slug}: the deck links to a file the demo does not ship; keep the samples self-contained`);
    }
    const fonts = [...html.matchAll(/url\(\s*['"]?fonts\/([A-Za-z0-9-]+\.woff2)/g)].map((m) => m[1]);
    for (const f of fonts) if (!existsSync(join(OUT, 'shared/fonts', f))) throw new Error(`${slug}: missing font ${f}`);
    const key = `units/${unitId}/index.html`;
    mkdirSync(join(OUT, 'units', String(unitId)), { recursive: true });
    writeFileSync(join(OUT, key), html);
    return {
      id: unitId, position: i + 1, title: meta.title_th, level: meta.level, slug, key,
      slides: countSlides(html), hashes: scriptHashes(html),
      sha256: createHash('sha256').update(html, 'utf8').digest('hex'), bytes: Buffer.byteLength(html),
    };
  }),
}));

mkdirSync(join(ROOT, 'src/demo'), { recursive: true });
writeFileSync(join(ROOT, 'src/demo/catalog.ts'), `// GENERATED by scripts/demo-build.mjs from kruslide/samples/. Do not edit: run \`node scripts/demo-build.mjs\`.
/** The demo's books: every unit is one real sample deck, shipped as a Workers Static Asset under \`key\`. */
export interface DemoUnit { id: number; position: number; title: string; level: string; slug: string; key: string; slides: number; hashes: string[]; sha256: string; bytes: number; }
export interface DemoBook { id: number; title: string; subject: string; grade: string; rate: number; units: DemoUnit[]; }

export const DEMO_BOOKS: DemoBook[] = ${JSON.stringify(catalog, null, 2)};
`);
const files = readdirSync(OUT, { recursive: true }).filter((f) => /\.\w+$/.test(f)).length;
console.log(`demo: ${catalog.length} books, ${unitId} units, ${files} files in demo/assets`);
for (const b of catalog) for (const u of b.units) console.log(`  unit ${u.id} ${u.slug}: ${u.slides} slides, ${u.hashes.length} script(s), ${(u.bytes / 1024).toFixed(0)} KB`);
